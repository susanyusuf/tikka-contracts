use soroban_sdk::{contracttype, Address, String};

/// Factory leaderboard sort key (#484).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[contracttype]
pub enum LeaderboardMetric {
    TicketsSold = 0,
    PrizeAmount = 1,
    TotalVolume = 2,
}

/// On-chain creator profile with display name, verified badge, and track record.
#[derive(Clone, Debug, PartialEq, Eq)]
#[contracttype]
pub struct CreatorProfile {
    pub name: String,
    pub verified: bool,
    pub raffles_created: u32,
}

/// Per-partner aggregate statistics for the partner dashboard API (#488).
#[derive(Clone, Debug, PartialEq, Eq)]
#[contracttype]
pub struct PartnerStats {
    /// Number of raffles created by this partner (both `create_raffle` and
    /// `trigger_next_round`).
    pub total_raffles: u32,
    /// Cumulative ticket-sale volume denominated in the payment asset(s) as
    /// reported by `record_volume` (net of discounts, gross of fees where
    /// applicable). Sums across all raffles the partner created.
    pub total_volume: i128,
    /// Cumulative protocol fees generated by ticket sales for this partner's
    /// raffles (basis points applied to volume at purchase time). Added by
    /// `record_volume` alongside `total_volume`.
    pub total_fees_generated: i128,
    /// Ledger timestamp (seconds) of the first time this partner created a
    /// raffle. Set on the partner's initial creation event.
    pub first_raffle_at: u64,
    /// Ledger timestamp (seconds) of the most recent raffle created by this
    /// partner. Updated on every creation.
    pub latest_raffle_at: u64,
}